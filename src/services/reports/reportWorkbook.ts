import ExcelJS from 'exceljs'
import { reportValue, type ReportColumn } from './reportDefinitions.js'

const BRAND = 'FF005390'
const MONEY_FMT = '[>=10000000]##\\,##\\,##\\,##0.00;[>=100000]##\\,##\\,##0.00;##,##0.00'
const NUMBER_FMT = '#,##0.##'
const DATE_FMT = 'dd-mmm-yyyy'
const DATETIME_FMT = 'dd-mmm-yyyy hh:mm AM/PM'
const MAX_WIDTH = 60

/** The table one file holds. */
export interface WorkbookTable {
  /** Shown as `<title> Report` at the top of the sheet. */
  title: string
  sheetName: string
  /** What the date range applies to; null when it doesn't apply (a current list). */
  dateBasis: string | null
  columns: ReportColumn[]
}

export interface ReportMeta {
  propertyName: string
  from: string
  to: string
  generatedBy: string
  /** Local (IST) wall-clock time the file was made. */
  generatedAt: Date
  filterText?: string | null
  truncatedAt?: number | null
}

/** A local `YYYY-MM-DD[ HH:MM:SS]` string as a Date whose UTC fields hold that wall-clock time (what Excel shows). */
const wallClock = (value: string) =>
  new Date(`${value.replace(' ', 'T').slice(0, 19)}${value.length > 10 ? '' : 'T00:00:00'}Z`)

const prettyDay = (ymd: string) =>
  wallClock(ymd).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric', timeZone: 'UTC' })

function cellValue(column: ReportColumn, raw: unknown): ExcelJS.CellValue {
  const value = reportValue(column, raw)
  if (typeof value === 'string' && (column.type === 'date' || column.type === 'datetime')) {
    const d = wallClock(value)
    return Number.isNaN(d.getTime()) ? value : d
  }
  return value
}

const textLength = (column: ReportColumn, value: ExcelJS.CellValue) => {
  if (value === null || value === undefined) return 0
  if (column.type === 'date') return 11
  if (column.type === 'datetime') return 20
  if (column.type === 'money') return Number(value).toFixed(2).length + 4
  return String(value).length
}

/** One sheet: a title block, then the header row, the rows and (when a column adds up) a totals row. */
export async function buildReportWorkbook(
  definition: WorkbookTable,
  rows: Record<string, unknown>[],
  meta: ReportMeta,
): Promise<ExcelJS.Workbook> {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = 'Rely Active'
  workbook.created = new Date()
  const sheet = workbook.addWorksheet(definition.sheetName.replace(/[*?:\\/[\]]/g, ' ').slice(0, 31))
  const { columns } = definition
  const lastCol = columns.length

  const info: string[] = [
    `Property: ${meta.propertyName}`,
    ...(definition.dateBasis
      ? [`Date range: ${prettyDay(meta.from)} to ${prettyDay(meta.to)}`, `Based on: ${definition.dateBasis}`]
      : ['The current list (the date range does not apply)']),
  ]
  if (meta.filterText) info.push(meta.filterText)
  info.push(
    `Generated by ${meta.generatedBy} on ${meta.generatedAt.toLocaleString('en-IN', {
      day: '2-digit',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      timeZone: 'UTC',
    })} IST`,
  )
  if (meta.truncatedAt) {
    info.push(
      `Only the first ${meta.truncatedAt.toLocaleString('en-IN')} rows are included. Choose a shorter date range for the rest.`,
    )
  }

  const title = sheet.addRow([`${definition.title} Report`])
  title.font = { bold: true, size: 14, color: { argb: BRAND } }
  sheet.mergeCells(title.number, 1, title.number, Math.max(lastCol, 1))
  for (const line of info) {
    const row = sheet.addRow([line])
    row.font = { size: 10, color: { argb: meta.truncatedAt && line === info.at(-1) ? 'FFB45309' : 'FF4B5563' } }
    sheet.mergeCells(row.number, 1, row.number, Math.max(lastCol, 1))
  }
  sheet.addRow([])

  const header = sheet.addRow(columns.map((c) => c.header))
  header.height = 20
  header.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND } }
    cell.alignment = { vertical: 'middle', wrapText: false }
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF003A66' } } }
  })
  const headerRow = header.number

  const widths = columns.map((c) => c.header.length)
  const totals = columns.map(() => 0)

  for (const raw of rows) {
    const values = columns.map((c) => cellValue(c, raw[c.key]))
    values.forEach((v, i) => {
      widths[i] = Math.max(widths[i] ?? 0, textLength(columns[i]!, v))
      if (columns[i]!.total && typeof v === 'number') totals[i]! += v
    })
    sheet.addRow(values)
  }

  if (rows.length === 0) {
    const empty = sheet.addRow([definition.dateBasis ? 'No records in this date range' : 'No records'])
    empty.font = { italic: true, color: { argb: 'FF6B7280' } }
    sheet.mergeCells(empty.number, 1, empty.number, Math.max(lastCol, 1))
  } else if (columns.some((c) => c.total)) {
    const firstTotal = columns.findIndex((c) => c.total)
    const totalRow = sheet.addRow(
      columns.map((c, i) => {
        if (c.total) return Math.round(totals[i]! * 100) / 100
        return i === 0 && firstTotal !== 0
          ? `Total (${rows.length.toLocaleString('en-IN')} ${rows.length === 1 ? 'row' : 'rows'})`
          : null
      }),
    )
    totalRow.font = { bold: true }
    totalRow.eachCell((cell) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE5EEF6' } }
      cell.border = { top: { style: 'thin', color: { argb: BRAND } } }
    })
  }

  columns.forEach((c, i) => {
    const col = sheet.getColumn(i + 1)
    col.width = Math.min(MAX_WIDTH, Math.max(10, (widths[i] ?? 10) + 2))
    if (c.type === 'money') col.numFmt = MONEY_FMT
    else if (c.type === 'number') col.numFmt = NUMBER_FMT
    else if (c.type === 'date') col.numFmt = DATE_FMT
    else if (c.type === 'datetime') col.numFmt = DATETIME_FMT
  })
  // The title block sits in column A; keep it from taking on a number format.
  for (let r = 1; r < headerRow; r++) sheet.getCell(r, 1).numFmt = 'General'

  sheet.views = [{ state: 'frozen', ySplit: headerRow }]
  if (rows.length > 0) {
    sheet.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow + rows.length, column: lastCol } }
  }
  return workbook
}
